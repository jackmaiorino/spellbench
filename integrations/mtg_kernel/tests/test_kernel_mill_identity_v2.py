def test_blocking3_carried_completion_repeats_evicted_preview_and_surfaces_refusal():
    """Blocking #3: after cache eviction, production repeats the preview and halts just like origin/main."""
    class RefuseRepeatPeer(DeterministicMillPeer):
        """Accepts every preview once; refuses a repeat of a previously evicted prefix."""

        def __init__(self, count):
            super().__init__(count)
            self.seen_previews = set()

        def request(self, request):
            if request["request_type"] == "preview_steps":
                key = tuple(request["candidate_ids"])
                if key in self.seen_previews:
                    return {"response_type": "error", "error": {"code": "refused", "message": "evicted repeat"}}
                self.seen_previews.add(key)
            return super().request(request)

    # Reviewer's exact scenario: 5-card mill with a 6,000-byte cache; pick 0 then step.
    ref_lines, ref_term = _run_sequence(
        RefuseRepeatPeer(5), [0, 0, 0], use_step=True, reference=True, cache_bound=6000
    )
    new_lines, new_term = _run_sequence(
        RefuseRepeatPeer(5), [0, 0, 0], use_step=True, reference=False, cache_bound=6000
    )
    assert new_lines == ref_lines
    assert new_term == ref_term
    # Confirm pick 0 succeeded as a decision and pick 1 halted on the refused repeat preview.
    assert json.loads(new_lines[0])["response_type"] == "decision"
    halted = json.loads(new_lines[1])
    assert halted["response_type"] == "terminal"
    assert halted["outcome"] == "halted"
    assert halted["reason"] == "engine_contract_failure:ProjectionError"

    # Complementary case: with a generous cache (no eviction), neither origin/main nor production repeats.
    ref_ok, ref_ok_term = _run_sequence(
        RefuseRepeatPeer(5), [0, 0, 0], use_step=True, reference=True,
        cache_bound=kernel_engine_v2.PREVIEW_CACHE_BYTES,
    )
    new_ok, new_ok_term = _run_sequence(
        RefuseRepeatPeer(5), [0, 0, 0], use_step=True, reference=False,
        cache_bound=kernel_engine_v2.PREVIEW_CACHE_BYTES,
    )
    assert new_ok == ref_ok
    assert new_ok_term == ref_ok_term
    assert json.loads(new_ok[1])["response_type"] == "decision"


def _make_arrangement_view(purpose, obs_json):
    if purpose == "discard_order":
        candidates = [{"candidate_id": i, "semantic": {
            "kind": "discard", "cards": [{"object_id": f"native-{i}"}]}} for i in range(2)]
        support = {"effect_instance": "eff-1", "discard_selected_count": 0,
                   "choice": {"purpose": "discard_order", "stage": "discard"}}
        result = {"graveyard": ("neutral-0", "neutral-1")}
    else:
        assert purpose == "put_on_top"
        candidates = [{"candidate_id": i, "semantic": {
            "kind": "choose_effect_target", "target": {"object": {"object_id": f"native-{i}"}}}}
            for i in range(2)]
        support = {"effect_instance": "eff-1", "hand_to_top": {"selected_count": 0, "total": 2, "remaining": 2},
                   "choice": {"purpose": "put_on_top", "stage": "top_order"}}
        result = {"top": ("neutral-0", "neutral-1")}
    view = {
        "game_id": "g-malformed",
        "candidates": candidates,
        "extensions": {
            "x_kernel_v2_support": support,
            "x_kernel_flat_v4": {"row_candidate_ids": [0, 1]},
            "x_kernel_v5": {"observation_json": obs_json},
        },
    }
    binding = native_arrangement_binding(view, {"neutral-0": "native-0", "neutral-1": "native-1"})
    return view, result, binding


