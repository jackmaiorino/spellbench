class DeterministicMillPeer(MillPeer):
    """MillPeer with sorted TENSOR_KEYS order so wire bytes are independent of PYTHONHASHSEED."""

    def view(self, prefix):
        v = super().view(prefix)
        t = v["extensions"][FLAT]["tensor"]
        v["extensions"][FLAT]["tensor"] = {k: t[k] for k in sorted(TENSOR_KEYS)}
        return v


class VariedTensorMillPeer(DeterministicMillPeer):
    """Synthetic mill peer with randomized dense/sparse/signed/bool tensor slices."""

    def __init__(self, count, seed, *, include_bools=False, non_ascii_key=False, width=16):
        rng = random.Random(seed)
        self._include_bools = include_bools
        self._non_ascii_key = non_ascii_key
        pool = [0, 0, 0, 1, -1, 1065353216, -2147483648, wire.MAX_JSON_INT]
        if include_bools:
            pool = pool + [True, False]
        self._card_rows = [[rng.choice(pool) if rng.random() < 0.7 else rng.getrandbits(31)
                            for _ in range(width)] for _ in range(count)]
        self._act_rows = [[rng.choice(pool) if rng.random() < 0.5 else rng.getrandbits(31)
                           for _ in range(width)] for _ in range(count)]
        self._base_state = [rng.choice(pool) for _ in range(48)]
        super().__init__(count)

    def view(self, prefix):
        v = super().view(prefix)
        if not hasattr(self, "_card_rows"):
            return v
        remaining = [i for i in range(self.count) if i not in prefix]
        state = list(self._base_state)
        state[0] = len(prefix)
        state[1] = sum((pos + 1) * (val + 3) for pos, val in enumerate(prefix))
        obj_order = remaining + list(prefix)
        obj_feats = [w for idx in obj_order for w in self._card_rows[idx]]
        act_feats = [w for idx in remaining for w in self._act_rows[idx]]
        tensor = v["extensions"][FLAT]["tensor"]
        tensor["state"] = state
        tensor["object_features"] = obj_feats
        tensor["action_features"] = act_feats
        tensor["object_groups"] = [5] * len(remaining) + [3] * len(prefix)
        if self._non_ascii_key:
            tensor["k_\u00e9"] = [0, 0, 0, 0, 0, 0, 0, 0, len(prefix)]
        return v


def _reference_pack(tensor):
    result = {}
    for key, values in tensor.items():
        runs = []
        for value in values:
            if runs and runs[-1][0] == value:
                runs[-1][1] += 1
            else:
                runs.append([value, 1])
        packed = {"length": len(values), "rle": runs}
        shorter = len(wire.canonical_json_dumps(packed)) < len(wire.canonical_json_dumps(values))
        result[key] = packed if shorter else values
    return result


def _reference_intern(proposals, grouped=False):
    vectors, keys, indices, indexed = [], [], {}, []
    for trajectory in proposals:
        steps = []
        for position, step in enumerate(trajectory):
            tensor = {}
            for key, words in step["tensor"].items():
                encoded = wire.canonical_json_dumps(words)
                if encoded not in indices:
                    indices[encoded] = len(vectors)
                    vectors.append(words)
                    keys.append((key, position))
                tensor[key] = {"vector": indices[encoded]}
            steps.append({"tensor": tensor, "selected_row": step["selected_row"]})
        indexed.append(steps)
    if grouped:
        order = sorted(range(len(vectors)), key=keys.__getitem__)
        rank = [0] * len(order)
        for new, old in enumerate(order):
            rank[old] = new
        vectors = [vectors[old] for old in order]
        for steps in indexed:
            for step in steps:
                for ref in step["tensor"].values():
                    ref["vector"] = rank[ref["vector"]]
    return {"vectors": vectors, "proposals": indexed}


def _reference_proposal_extension(engine, actor, candidate_count):
    """Verbatim pre-change proposal_extension from origin/main (41f0f75)."""
    proposals = []
    for candidate in range(candidate_count):
        plan = deepcopy(engine.buffer)
        finished = plan.choose(candidate)
        while not finished:
            finished = plan.choose(0)
        if isinstance(plan, TriggerOrder):
            selected = plan.result()
            flat = engine.root["extensions"][FLAT]
            proposals.append([{"tensor": _reference_pack(flat["tensor"]),
                "selected_row": flat["row_candidate_ids"].index(selected)}])
            continue
        if isinstance(plan, BlockDeclaration):
            binding = legacy_block_assignment(engine.root, plan.plan, plan.assignment())
            pick = lambda view: native_block_pick(view, binding)
        else:
            binding = native_arrangement_binding(engine.root, engine.arrangement_cards)
            result = plan.result()
            pick = lambda view: native_arrangement_pick(view, result, binding)
        entry = engine.previews.get(()) or engine.previews.put((), [engine.root, None], 0)
        prefix, steps = [], []
        for _ in range(4096):
            view = entry[0]
            selected = pick(view)
            flat = view["extensions"][FLAT]
            if entry[1] is None:
                entry[1] = _reference_pack(flat["tensor"])
            steps.append({"tensor": entry[1], "selected_row": flat["row_candidate_ids"].index(selected)})
            prefix.append(selected)
            key = tuple(prefix)
            entry = engine.previews.get(key)
            if entry is None:
                answer = engine.peer.request({"request_type": "preview_steps", "game_id": engine.game,
                    "expected_step": engine.root["step"], "candidate_ids": prefix})
                if answer["response_type"] == "error":
                    raise ProjectionError("private completion preview refused within its declaration")
                if answer["response_type"] not in ("private_complete", "private_preview"):
                    raise ProjectionError("private completion preview returned an unexpected response")
                view = answer["view"] if answer["response_type"] == "private_preview" else None
                size = getattr(engine.peer, "last_line_bytes", None)
                entry = engine.previews.put(key, [view, None], len(json.dumps(answer)) if size is None else size)
            if entry[0] is None:
                break
        else:
            raise ProjectionError("private completion preview exceeded its bound")
        proposals.append(steps)
    original = engine.root["extensions"][FLAT]
    extension = {"schema": kernel_engine_v2.PROPOSALS, "mapping": "deterministic-completion-logprob/v1",
        "tensor_encoding": kernel_engine_v2.PROPOSAL_ENCODING,
        **{key: original[key] for key in ("card_db_hash", "feature_contract_digest", "feature_encoding_digest")},
        "acting_seat": actor, "step": engine.seat_steps[actor],
        "row_candidate_ids": list(range(candidate_count))}
    limit = wire.MAX_LINE_BYTES - 262144
    smallest = None
    for grouped, level in ((False, 1), (False, 9), (True, 9)):
        if level == 1 or grouped:
            payload = wire.canonical_json_dumps(_reference_intern(proposals, grouped=grouped))
            if len(payload) > 64 * 1024 * 1024:
                raise ProjectionError("completion proposal exceeds the decoded payload bound")
        encoded = base64.b64encode(zlib.compress(payload, level=level)).decode("ascii")
        if smallest is None or len(encoded) < len(smallest):
            smallest = encoded
        extension["proposals_zlib"] = encoded
        if len(wire.canonical_json_dumps(extension)) <= limit * 3 // 4:
            break
    else:
        extension["proposals_zlib"] = smallest
    extension_bytes = len(wire.canonical_json_dumps(extension))
    if extension_bytes > limit:
        raise ProjectionError(f"completion proposal exceeds the wire bound: "
            f"decoded={len(payload)} encoded_extension={extension_bytes} "
            f"limit={limit} candidates={candidate_count} "
            f"steps={sum(map(len, proposals))}")
    return extension


def _wire_engine(peer):
    engine = engine_for(peer)
    engine.previews = None
    engine.pending = None
    engine.max_steps = engine.max_groups = 10000
    return engine


def _run_sequence(peer, picks, *, use_step=True, reference=False, cache_bound=None):
    engine = _wire_engine(peer)
    orig_pe = KernelEngine.proposal_extension
    orig_bound = PreviewCache.__init__.__defaults__
    if reference:
        KernelEngine.proposal_extension = _reference_proposal_extension
    if cache_bound is not None:
        PreviewCache.__init__.__defaults__ = (cache_bound,)
    lines = []
    try:
        ans = engine.pose("step-0")
        lines.append(wire.canonical_json_line(ans))
        for idx, pick in enumerate(picks, 1):
            if use_step:
                sd = ans["seat_decision"]
                ans = engine.step({
                    "request_id": f"step-{idx}", "game_id": "synthetic-mill",
                    "expected_step": engine.answered,
                    "selection": {"candidate_id": pick, "semantic_echo": sd["candidates"][pick]["semantic"]},
                })
            else:
                engine.buffer.choose(pick)
                ans = engine.pose(f"step-{idx}")
            lines.append(wire.canonical_json_line(ans))
        if use_step and len(picks) == peer.count - 2:
            sd = ans["seat_decision"]
            term = engine.step({
                "request_id": "step-final", "game_id": "synthetic-mill",
                "expected_step": engine.answered,
                "selection": {"candidate_id": 0, "semantic_echo": sd["candidates"][0]["semantic"]},
            })
            terminal_line = wire.canonical_json_line(term)
        else:
            while len(engine.buffer.order) < engine.buffer.count - 1:
                engine.buffer.choose(0)
            engine.commit_buffer()
            terminal_line = wire.canonical_json_line(engine.current)
    finally:
        KernelEngine.proposal_extension = orig_pe
        PreviewCache.__init__.__defaults__ = orig_bound
    return lines, terminal_line


def test_whole_library_mill_matches_recorded_baseline_step_by_step():
    """Every step of a 40-card whole-library mill matches pre-change origin/main digests byte-for-byte."""
    lines, term = _run_sequence(DeterministicMillPeer(40), MILL_40_PICKS, use_step=True, reference=False)
    assert len(lines) == len(MILL_40_BASELINE_STEP_DIGESTS) == 39
    for idx, (line, expected_digest) in enumerate(zip(lines, MILL_40_BASELINE_STEP_DIGESTS)):
        assert hashlib.sha256(line).hexdigest() == expected_digest, f"step {idx} diverged from baseline"
    assert hashlib.sha256(term).hexdigest() == MILL_40_BASELINE_TERM_DIGEST


def test_existing_buffered_mill_fixtures_are_byte_identical_step_by_step(monkeypatch):
    """The existing buffered-mill and preview-cache fixtures produce byte-identical wire answers."""
    for count, picks, use_step in (
        (60, [59], False),
        (12, [11, 0, 5, 3, 0, 2], False),
        (12, [11, 0, 5, 3, 0, 2], True),
        (30, [0] * 10 + [7, 18, 1], False),
    ):
        ref_lines, ref_term = _run_sequence(MillPeer(count), picks, use_step=use_step, reference=True)
        new_lines, new_term = _run_sequence(MillPeer(count), picks, use_step=use_step, reference=False)
        assert new_lines == ref_lines
        assert new_term == ref_term

    # Tight wire bound and over-limit path (from test_kernel_buffered_mill_v2.py).
    plain_ref, _ = _run_sequence(MillPeer(20), [], use_step=False, reference=True)
    plain_new, _ = _run_sequence(MillPeer(20), [], use_step=False, reference=False)
    assert plain_new == plain_ref
    plain_ext_size = len(wire.canonical_json_dumps(
        json.loads(plain_ref[0])["seat_decision"]["extensions"][FLAT]))
    monkeypatch.setattr(wire, "MAX_LINE_BYTES", 262144 + plain_ext_size * 4 // 3 - 8)
    tight_ref, _ = _run_sequence(MillPeer(20), [0, 3], use_step=True, reference=True)
    tight_new, _ = _run_sequence(MillPeer(20), [0, 3], use_step=True, reference=False)
    assert tight_new == tight_ref

    monkeypatch.setattr(wire, "MAX_LINE_BYTES", 262144 + 1024)
    with pytest.raises(ProjectionError, match="exceeds the wire bound"):
        _run_sequence(MillPeer(20), [], use_step=False, reference=False)


@pytest.mark.parametrize("seed", range(6))
def test_randomized_mill_equivalence_across_seeds(seed, monkeypatch):
    """Randomized library sizes, tensors, picks, cache bounds and wire limits match reference byte-for-byte."""
    rng = random.Random(seed)
    count = rng.randint(5, 16)
    mode = seed % 3
    if mode == 0:
        picks = [0] * (count - 2)  # repeated candidate-0 hits carried completions every pick
    elif mode == 1:
        picks = [count - 1 - p for p in range(count - 2)]  # always last candidate
    else:
        picks = [rng.randrange(count - p) for p in range(count - 2)]
    include_bools = (seed == 4)
    non_ascii_key = (seed == 5)
    cache_bound = [0, 20000, kernel_engine_v2.PREVIEW_CACHE_BYTES][seed % 3]
    use_step = bool(seed % 2)
    peer_factory = lambda: VariedTensorMillPeer(
        count, seed=100 + seed, include_bools=include_bools, non_ascii_key=non_ascii_key, width=18)

    # Probe pick-0 extension sizes under normal limit so we can pick a tight limit
    # that forces (False, 9), (True, 9), or the else/smallest branch on some seeds.
    base_ref, _ = _run_sequence(peer_factory(), [], use_step=False, reference=True)
    ext_size = len(wire.canonical_json_dumps(json.loads(base_ref[0])["seat_decision"]["extensions"][FLAT]))
    if seed in (1, 2):
        # Force past the 3/4 margin so (False, 9) and/or (True, 9) run.
        monkeypatch.setattr(wire, "MAX_LINE_BYTES", 262144 + ext_size * 4 // 3 - 16)
    elif seed == 3:
        # Very tight margin that forces all three encodings past margin (else/smallest branch),
        # while still fitting under the hard wire limit.
        monkeypatch.setattr(wire, "MAX_LINE_BYTES", 262144 + ext_size + 64)

    ref_lines, ref_term = _run_sequence(peer_factory(), picks, use_step=use_step, reference=True,
                                        cache_bound=cache_bound)
    new_lines, new_term = _run_sequence(peer_factory(), picks, use_step=use_step, reference=False,
                                        cache_bound=cache_bound)
    assert new_lines == ref_lines
    assert new_term == ref_term


def test_bounded_deflate_matches_original_three_pass_loop_on_all_branches_and_ties():
    """Chunked pause/resume _BoundedDeflate matches zlib.compress and selects identical smallest on ties."""
    rng = random.Random(77)
    for size in (0, 17, 65535, 65536, 65537, 180000):
        data = bytes(rng.choices(b"0123456789,[]:{}abcdef", k=size))
        for level in (1, 9):
            ref = zlib.compress(data, level=level)
            bd_full = _BoundedDeflate(data, level)
            assert bd_full.run_until(len(ref)) == ref
            if len(ref) > 1:
                bd_pause = _BoundedDeflate(data, level)
                assert bd_pause.run_until(len(ref) - 1) is None
                # Resuming from pause still yields exact zlib.compress bytes.
                assert bd_pause.run_until(len(ref)) == ref

    # Verify Case D tie-breaking logic against the original loop over all byte-length triples
    # (including same-base64-block ties like 4 vs 5 bytes -> both 8 base64 chars).
    for l1 in (3, 4, 5, 6, 7):
        for l9 in (3, 4, 5, 6, 7):
            for lg in (3, 4, 5, 6, 7):
                c1, c9, cg = b"a" * l1, b"b" * l9, b"c" * lg
                # Original loop else-branch: smallest by len(b64), earliest wins ties.
                smallest = None
                for raw in (c1, c9, cg):
                    enc = base64.b64encode(raw).decode("ascii")
                    if smallest is None or len(enc) < len(smallest):
                        smallest = enc
                # New Case D selection:
                best = cg
                best_blocks = (len(cg) + 2) // 3
                if len(c1) <= 3 * best_blocks:
                    best = c1
                    c9_cap = 3 * ((len(c1) + 2) // 3 - 1)
                else:
                    c9_cap = 3 * best_blocks
                if len(c9) <= c9_cap:
                    best = c9
                assert base64.b64encode(best).decode("ascii") == smallest
