def test_randomized_mill_equivalence_covers_all_compression_branches(monkeypatch):
    """Randomized mills match origin/main byte-for-byte and provably reach all 4 compression branches."""
    branches_hit = set()
    for seed in range(8):
        rng = random.Random(seed)
        count = rng.randint(6, 12)
        mode = seed % 3
        if mode == 0:
            picks = [0] * (count - 2)
        elif mode == 1:
            picks = [count - 1 - p for p in range(count - 2)]
        else:
            picks = [rng.randrange(count - p) for p in range(count - 2)]
        include_bools = (seed == 4)
        non_ascii_key = (seed in (5, 6))
        extra_keys = ["k_del\x7f", "k_tab\t"] if seed == 7 else ()
        cache_bound = [0, 20000, kernel_engine_v2.PREVIEW_CACHE_BYTES][seed % 3]
        use_step = bool(seed % 2)
        width = 36 if seed in (2, 3, 6, 7) else 18
        peer_factory = lambda c=count, s=seed, ib=include_bools, na=non_ascii_key, ek=extra_keys, w=width: (
            VariedTensorMillPeer(c, seed=100 + s, include_bools=ib, non_ascii_key=na,
                                 extra_keys=ek, width=w, state_width=96)
        )

        # Measure real 3-pass sizes on pick 0 so seeds deterministically hit u1, u9, g9, and fallback.
        base_len, u1_len, u9_len, g9_len, b64_u1, b64_u9, b64_g9, _, _ = _probe_three_pass_sizes(peer_factory)
        target_branch = seed % 4  # 0: u1, 1: u9, 2: g9, 3: fallback
        if target_branch == 0:
            limit = wire.MAX_LINE_BYTES - 262144
        elif target_branch == 1:
            # Force u1 > margin while u9 <= margin.
            assert u9_len < u1_len
            limit = (u9_len * 4 + 2) // 3 + 4
            assert u9_len <= limit * 3 // 4 < u1_len
        elif target_branch == 2:
            # Force u1, u9 > margin while g9 <= margin.
            assert g9_len < u9_len
            limit = (g9_len * 4 + 2) // 3 + 4
            assert g9_len <= limit * 3 // 4 < u9_len
        else:
            # Force all three > margin while smallest <= limit (smallest-output fallback).
            smallest_len = min(u1_len, u9_len, g9_len)
            limit = smallest_len + 16
            assert limit * 3 // 4 < smallest_len <= limit

        with monkeypatch.context() as mp:
            if target_branch != 0:
                mp.setattr(wire, "MAX_LINE_BYTES", 262144 + limit)
            ref_lines, ref_term = _run_sequence(
                peer_factory(), picks, use_step=use_step, reference=True, cache_bound=cache_bound
            )
            new_lines, new_term = _run_sequence(
                peer_factory(), picks, use_step=use_step, reference=False, cache_bound=cache_bound
            )
            assert new_lines == ref_lines
            assert new_term == ref_term
            ext0_b64 = json.loads(new_lines[0])["seat_decision"]["extensions"][FLAT]["proposals_zlib"]
            branch = _classify_branch(ext0_b64, limit, base_len, b64_u1, b64_u9, b64_g9)
            branches_hit.add(branch)

    assert branches_hit == {"u1", "u9", "g9", "fallback"}
