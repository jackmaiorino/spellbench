def test_blocking5_memory_bound_totals_all_caches_and_zero_bound_disables_them():
    """Blocking #5: carried state and all new caches share PreviewCache.bound in total; bound=0 disables them."""
    # 1. Reviewer's 5-card fixture with a 150,000-byte bound and large tensors.
    bound = 150_000
    peer = VariedTensorMillPeer(5, seed=55, width=64, state_width=512)
    engine = _wire_engine(peer)
    orig_bound = PreviewCache.__init__.__defaults__
    PreviewCache.__init__.__defaults__ = (bound,)
    try:
        ans = engine.pose("step-0")
        for idx, pick in enumerate([0, 0, 0], 1):
            cache = engine.previews
            max_entry = max((size for _, size in cache.entries.values()), default=0)
            assert cache.bytes <= max(bound, max_entry)
            if cache.meta or cache.key_cache or cache.carried:
                assert cache.bytes <= bound
            # Count raw encoded bytes retained across meta + key_cache + carried (carried holds none).
            raw_retained = (
                sum(sum(len(b) for b in m[0].values()) for m in cache.meta.values() if m[0] is not None)
                + sum(len(kc[2]) for kc in cache.key_cache.values())
            )
            assert cache._entry_bytes + raw_retained <= bound
            sd = ans["seat_decision"]
            ans = engine.step({
                "request_id": f"step-{idx}", "game_id": "synthetic-mill",
                "expected_step": engine.answered,
                "selection": {"candidate_id": pick, "semantic_echo": sd["candidates"][pick]["semantic"]},
            })
    finally:
        PreviewCache.__init__.__defaults__ = orig_bound

    # 2. Zero bound completely disables carried state, meta, and key_cache.
    peer0 = VariedTensorMillPeer(5, seed=55, width=64, state_width=512)
    engine0 = _wire_engine(peer0)
    PreviewCache.__init__.__defaults__ = (0,)
    try:
        ans0 = engine0.pose("zero-0")
        for idx, pick in enumerate([0, 1], 1):
            cache0 = engine0.previews
            assert cache0.key_cache == {}
            assert cache0.meta == {}
            assert cache0.carried == {}
            assert cache0.carried_order == []
            assert cache0._meta_bytes == 0
            assert cache0._key_cache_bytes == 0
            assert cache0._carried_bytes == 0
            sd0 = ans0["seat_decision"]
            ans0 = engine0.step({
                "request_id": f"zero-{idx}", "game_id": "synthetic-mill",
                "expected_step": engine0.answered,
                "selection": {"candidate_id": pick, "semantic_echo": sd0["candidates"][pick]["semantic"]},
            })
    finally:
        PreviewCache.__init__.__defaults__ = orig_bound


